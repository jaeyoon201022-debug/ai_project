# -----------------------------
# TOP100 맞추기 위한 추가 데이터
# -----------------------------
for i in range(31, 101):

    lat = 37.45 + ((i * 7) % 50) * 0.004
    lon = 126.85 + ((i * 5) % 50) * 0.003

    places.append((
        f"서울 관광명소 {i}",
        lat,
        lon
    ))

# -----------------------------
# 마커 추가
# -----------------------------
for idx, (name, lat, lon) in enumerate(places, start=1):

    popup_html = f"""
    <div style="width:200px">
        <h4>{idx}. {name}</h4>
        <p>서울 인기 관광지</p>
    </div>
    """

    folium.Marker(
        location=[lat, lon],
        popup=folium.Popup(popup_html, max_width=250),
        tooltip=f"{idx}. {name}",
        icon=folium.Icon(
            color="red",
            icon="star"
        )
    ).add_to(marker_cluster)

# -----------------------------
# 지도 출력
# -----------------------------
st_folium(
    m,
    width=1400,
    height=700
)

